def generate_markdown(code: str, q: dict) -> str:
    """生成 Markdown 格式的题目文件"""
    lines = [
        f'# 人工智能训练师(三级)操作技能考核 试题单',
        '',
        f'**准考证号**: __________  ',
        f'**试题代码**: {code}  ',
        f'**试题名称**: {q["name"]}  ',
        f'**考核时间**: {q["time"]}',
        '',
        '---',
        '',
        '## 1. 场地设备要求',
        '',
        q['equipment'],
        '',
        '---',
        '',
        '## 2. 工作任务',
        '',
        q['task'],
        '',
        '---',
        '',
        '## 3. 技能要求',
        '',
        q['skills'],
        '',
        '---',
        '',
        '## 4. 质量指标',
        '',
        q['quality'],
        '',
        '---',
        '',
        '## 5. 评分细则',
        '',
        '| 编号 | 配分 | 评分细则描述 | 得分 |',
        '|------|------|-------------|------|',
    ]
    
    for item_id, score, desc in q['scoring']:
        lines.append(f"| {item_id} | {score} | {desc} | |")
    
    lines.extend([
        f"| **合计** | **{q['total_score']}** | **合计得分** | |",
        '',
    ])
    
    return '\n'.join(lines)


