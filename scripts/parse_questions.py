def parse_questions():
    """解析题目数据"""
    questions = []
    
    for line in QUESTIONS_DATA.strip().split('\n'):
        if not line.strip():
            continue
        
        parts = line.split('|')
        if len(parts) < 5:
            continue
        
        code = parts[0].strip()
        name = parts[1].strip()
        time = parts[2].strip()
        task = parts[3].strip()
        scoring = parts[4].strip()
        
        # 解析评分细则
        scoring_items = []
        for item in scoring.split(';'):
            item = item.strip()
            if not item:
                continue
            if item.startswith('合计'):
                total_score = item.split(':')[1].strip()
                continue
            
            # 格式: M1:1:描述
            item_parts = item.split(':', 2)
            if len(item_parts) == 3:
                scoring_items.append({
                    'id': item_parts[0],
                    'score': item_parts[1],
                    'description': item_parts[2]
                })
        
        questions.append({
            'code': code,
            'name': name,
            'time': time,
            'task': task,
            'scoring': scoring_items,
            'total_score': total_score
        })
    
    return questions


