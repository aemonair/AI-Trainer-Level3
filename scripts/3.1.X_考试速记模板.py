import pandas as pd

# ============================================
# 步骤1：读取数据
# ============================================
df = pd.read_excel('数据文件.xlsx')
print(df.columns)  # 查看列名
print(df.head())   # 查看前5行

# ============================================
# 步骤2：提取小时 + 定义时间段
# ============================================
df['hour'] = pd.to_datetime(df['时间列名']).dt.hour

def get_period(h):
    if 6 <= h < 12: return '06:00-12:00'
    if 12 <= h < 18: return '13:00-18:00'
    return '19:00-05:00'

df['period'] = df['hour'].apply(get_period)

# ============================================
# 步骤3：统计频率（计数）
# ============================================
# 功能/场景使用频率
counts = df['功能列名'].value_counts()
print(counts)  # 降序排列

# 前3个最常用
print(counts.head(3))

# ============================================
# 步骤4：计算平均值
# ============================================
# 按时间段分组统计
stats = df.groupby('period')[['数值列1', '数值列2']].mean()
print(stats)

# 单个平均值
print(df['响应时间列'].mean())

# ============================================
# 步骤5：按功能统计平均响应时间
# ============================================
avg_response = df.groupby('功能列名')['响应时间列'].mean()
print(avg_response.sort_values(ascending=False))

# ============================================
# 步骤6：统计非空数据量
# ============================================
print(df['列名'].notna().sum())

